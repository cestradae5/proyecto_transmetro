import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { useAuth } from "../authentication/auth-context";
import { useReportDownload } from "./hooks/use-report-download";
import { canViewAdministrativeReports, canViewAuditLog } from "./permissions";

const CONTROL =
  "px-3 py-2 border border-slate-200 rounded-xl text-sm bg-white focus:outline-none focus:ring-2 focus:ring-primary/30";
const RANGE_ERROR = "La fecha inicial no puede ser posterior a la fecha final.";

interface ReportCardProps {
  title: string;
  icon: string;
  desc: string;
  busy: boolean;
  disabled?: boolean;
  onDownload: () => void;
  children?: React.ReactNode;
}

function ReportCard({ title, icon, desc, busy, disabled, onDownload, children }: ReportCardProps) {
  return (
    <section className="flex flex-col gap-3 p-5 rounded-2xl border border-slate-200 bg-slate-50/50">
      <div className="flex items-center gap-3">
        <span className="material-symbols-outlined text-[22px] text-purple-700">{icon}</span>
        <h2 className="font-display font-bold text-sm text-slate-900">{title}</h2>
      </div>
      <p className="text-xs text-slate-500">{desc}</p>
      {children}
      <button
        type="button"
        aria-label={`Descargar PDF: ${title}`}
        onClick={onDownload}
        disabled={busy || disabled}
        className="mt-auto self-start inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-primary text-white text-sm font-medium hover:opacity-90 disabled:opacity-50 disabled:cursor-not-allowed"
      >
        <span className="material-symbols-outlined text-[18px]">download</span>
        {busy ? "Generando…" : "Descargar PDF"}
      </button>
    </section>
  );
}

const SIMPLE_REPORTS = [
  { key: "fleet", title: "Flota", icon: "directions_bus", desc: "Unidades por estado, con su línea y piloto asignados.", fallback: "reporte-flota.pdf" },
  { key: "personnel", title: "Personal", icon: "badge", desc: "Empleados agrupados por rol, con su estado.", fallback: "reporte-personal.pdf" },
  { key: "infrastructure", title: "Infraestructura", icon: "route", desc: "Líneas con sus municipios, paradas y estaciones.", fallback: "reporte-infraestructura.pdf" },
] as const;

/** Submodule "Reportes administrativos": each report downloads as a PDF generated by the API. */
export function AdministrativeReportsPage() {
  const navigate = useNavigate();
  const { user } = useAuth();
  const { downloading, error, download } = useReportDownload();
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");

  const rangeInvalid = Boolean(from && to && from > to);
  const rangeIncomplete = !from || !to;

  return (
    <div className="min-h-screen bg-[#fafbfc]">
      <header className="w-full h-16 border-b border-slate-100 flex items-center justify-between px-6 lg:px-12 bg-white/95 backdrop-blur-sm z-30 shrink-0 fixed top-0 left-0">
        <div className="flex items-center gap-4">
          <button aria-label="Volver" onClick={() => navigate("/reports")} className="text-slate-600 hover:text-slate-900">
            <span className="material-symbols-outlined">arrow_back</span>
          </button>
          <span className="font-display font-bold text-xl text-primary">Transmetro</span>
        </div>
      </header>

      <main className="pt-20 md:pt-24 px-4 sm:px-8 py-8 lg:py-12 max-w-6xl mx-auto">
        <div className="bg-white rounded-3xl border border-slate-200/70 shadow-[0_10px_30px_-5px_rgba(0,0,0,0.04)] p-6 sm:p-11">
          <h1 className="font-display font-bold text-2xl sm:text-[28px] text-slate-900 tracking-tight mb-1">
            Reportes administrativos
          </h1>
          <p className="text-sm text-slate-500 mb-6">Genere y descargue reportes en formato PDF con los datos actuales del sistema.</p>

          {error && (
            <div role="alert" className="mb-4 p-3 bg-red-50 border border-red-200 rounded-lg text-red-700 text-sm">
              {error}
            </div>
          )}

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {canViewAdministrativeReports(user) &&
              SIMPLE_REPORTS.map((report) => (
                <ReportCard
                  key={report.key}
                  title={report.title}
                  icon={report.icon}
                  desc={report.desc}
                  busy={downloading === report.key}
                  onDownload={() => download(report.key, `/reports/${report.key}`, report.fallback)}
                />
              ))}

            {canViewAuditLog(user) && (
              <ReportCard
                title="Resumen de bitácora"
                icon="history"
                desc="Acciones registradas por módulo y por usuario en un rango de fechas."
                busy={downloading === "audit-log"}
                disabled={rangeIncomplete || rangeInvalid}
                onDownload={() =>
                  download(
                    "audit-log",
                    `/reports/audit-log?${new URLSearchParams({ from, to }).toString()}`,
                    `reporte-bitacora-${from}_${to}.pdf`,
                  )
                }
              >
                <div className="flex flex-wrap gap-3">
                  <label className="flex flex-col text-xs text-slate-600 gap-1">
                    Desde
                    <input type="date" className={CONTROL} value={from} max={to || undefined}
                      onChange={(e) => setFrom(e.target.value)} />
                  </label>
                  <label className="flex flex-col text-xs text-slate-600 gap-1">
                    Hasta
                    <input type="date" className={CONTROL} value={to} min={from || undefined}
                      onChange={(e) => setTo(e.target.value)} />
                  </label>
                </div>
                {rangeInvalid && <p className="text-xs text-red-600">{RANGE_ERROR}</p>}
              </ReportCard>
            )}
          </div>
        </div>
      </main>
    </div>
  );
}
