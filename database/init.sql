    estado_parada VARCHAR(20) NOT NULL CHECK (estado_parada IN ('ACTIVA', 'CERRADA', 'MANTENIMIENTO'))
);

CREATE TABLE IF NOT EXISTS tbl_estacion (
    id_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estacion VARCHAR(120) NOT NULL,
    latitud DECIMAL(10,8) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud DECIMAL(11,8) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    estado_estacion VARCHAR(30) NOT NULL,
    id_parada BIGINT UNIQUE,
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada)
