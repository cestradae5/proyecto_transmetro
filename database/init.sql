CREATE TABLE IF NOT EXISTS tbl_bitacora (
    id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modulo VARCHAR(60) NOT NULL,
    accion VARCHAR(80) NOT NULL,
    entidad_tipo VARCHAR(60) NOT NULL,
    entidad_id BIGINT,
    resultado VARCHAR(30) NOT NULL CHECK (resultado IN ('EXITOSO', 'FALLIDO', 'ERROR')),
    id_empleado BIGINT,
    detalle JSONB,
    FOREIGN KEY (id_empleado) REFERENCES tbl_empleado (id_emple)
);

-- ---------------------------------------------------------------------------
-- Evolución de bases existentes
-- ---------------------------------------------------------------------------
-- `CREATE TABLE IF NOT EXISTS` es un no-op cuando la tabla ya existe: correr
-- este archivo contra una base creada con una versión anterior de init.sql NO
-- agrega columnas nuevas. Para que una base existente alcance el esquema de
-- arriba sin scripts separados, cada columna agregada después del esquema
-- inicial se declara aquí con su ALTER idempotente.
--
-- `IF NOT EXISTS` los hace seguros de re-ejecutar: correr init.sql completo
-- varias veces sobre la misma base no falla ni altera nada.
--
-- tbl_bitacora.detalle JSONB — nullable, sin default. Requisito del módulo
-- fleet: cada mutación registra su payload estructurado. Las filas de
-- auditoría de auth escritas antes de esta columna conservan detalle = NULL.

ALTER TABLE tbl_bitacora ADD COLUMN IF NOT EXISTS detalle JSONB;

-- tbl_bitacora.id_empleado / entidad_id — nullable. Un login fallido se
-- registra solo como "ocurrió un intento": sin empleado, sin entidad y sin el
-- correo intentado. DROP NOT NULL es idempotente (no falla si ya es nullable),
-- así que las bases existentes se actualizan al re-aplicar este archivo.

ALTER TABLE tbl_bitacora ALTER COLUMN id_empleado DROP NOT NULL;
ALTER TABLE tbl_bitacora ALTER COLUMN entidad_id DROP NOT NULL;

-- tbl_empleado: perfil de RR. HH. del módulo Personal. Todas las columnas son
-- nullable para que las filas existentes (p. ej. el admin del seed) sigan
-- funcionando. La API exige el DPI como obligatorio; la columna queda nullable
-- solo por compatibilidad con filas legacy. El índice único parcial garantiza
-- que el DPI no se repita cuando está presente.

ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS telefono_emple VARCHAR(20);
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS dpi_emple VARCHAR(13);
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS fecha_ingreso_emple DATE;
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS direccion_emple VARCHAR(255);
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS licencia_emple VARCHAR(30);
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS historial_educativo_emple TEXT;
ALTER TABLE tbl_empleado ADD COLUMN IF NOT EXISTS idiomas_emple TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS idx_empleado_dpi ON tbl_empleado (dpi_emple) WHERE dpi_emple IS NOT NULL;

-- tbl_alerta.id_linea — nullable. Línea desde la que se envió la alerta,
-- fijada al crearla (la línea asignada a la unidad en ese momento). Una
-- estación solo ve las alertas de sus líneas ACTIVAS. La columna se agrega y
-- las alertas existentes se completan una sola vez, con la línea actual de su
-- unidad; las de unidades sin línea quedan en NULL (solo visibles en la vista
-- central, en "Sin línea"). Re-aplicar este archivo no repite el backfill.

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'tbl_alerta'
           AND column_name = 'id_linea'
    ) THEN
        ALTER TABLE tbl_alerta
            ADD COLUMN id_linea BIGINT REFERENCES tbl_linea (id_linea);
        UPDATE tbl_alerta a
           SET id_linea = au.id_linea
          FROM tbl_asignacion_unidad au
         WHERE au.id_unidad = a.id_unidad;
    END IF;
END
$$;


-- tbl_alerta.id_empleado — nullable. Las alertas que genera el sistema (por
-- ejemplo, capacidad de estación al pasar una talanquera) no tienen autor.

ALTER TABLE tbl_alerta ALTER COLUMN id_empleado DROP NOT NULL;

-- tbl_evento_talanquera.clave_idempotencia — nullable, UNIQUE. Clave que
-- envía la talanquera para que un reintento de la misma pasada no cobre ni
-- registre dos veces. Las pasadas sin clave no se deduplican.

ALTER TABLE tbl_evento_talanquera ADD COLUMN IF NOT EXISTS clave_idempotencia VARCHAR(64) UNIQUE;

-- Conteo por parada. El conteo, la capacidad y la alerta del 150% son de la
-- parada; una estación usa los de su parada (tbl_estacion.id_parada).
--
-- tbl_parada.capacidad_pasajeros — personas que la parada admite esperando.
-- Si la estación ya tenía capacidad propia (versión anterior de este
-- archivo), se copia una sola vez a su parada y la columna de la estación se
-- elimina. Eventos de talanquera y detenciones de unidades pasan de
-- id_estacion a id_parada, convertidos a través de tbl_estacion.id_parada.
-- Las alertas de capacidad guardan la parada en tbl_alerta.id_parada_origen.

ALTER TABLE tbl_parada ADD COLUMN IF NOT EXISTS capacidad_pasajeros INTEGER NOT NULL DEFAULT 100 CHECK (capacidad_pasajeros > 0);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'tbl_estacion' AND column_name = 'capacidad_pasajeros'
    ) THEN
        UPDATE tbl_parada p
           SET capacidad_pasajeros = e.capacidad_pasajeros
          FROM tbl_estacion e
         WHERE e.id_parada = p.id_parada;
        ALTER TABLE tbl_estacion DROP COLUMN capacidad_pasajeros;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'tbl_evento_talanquera' AND column_name = 'id_estacion'
    ) THEN
        ALTER TABLE tbl_evento_talanquera
            ADD COLUMN id_parada BIGINT REFERENCES tbl_parada (id_parada);
        UPDATE tbl_evento_talanquera ev
           SET id_parada = e.id_parada
          FROM tbl_estacion e
         WHERE e.id_estacion = ev.id_estacion;
        ALTER TABLE tbl_evento_talanquera ALTER COLUMN id_parada SET NOT NULL;
        ALTER TABLE tbl_evento_talanquera DROP COLUMN id_estacion;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'tbl_parada_unidad' AND column_name = 'id_estacion'
    ) THEN
        ALTER TABLE tbl_parada_unidad
            ADD COLUMN id_parada BIGINT REFERENCES tbl_parada (id_parada);
        UPDATE tbl_parada_unidad pu
           SET id_parada = e.id_parada
          FROM tbl_estacion e
         WHERE e.id_estacion = pu.id_estacion;
        ALTER TABLE tbl_parada_unidad ALTER COLUMN id_parada SET NOT NULL;
        ALTER TABLE tbl_parada_unidad DROP COLUMN id_estacion;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'tbl_alerta' AND column_name = 'id_parada_origen'
    ) THEN
        ALTER TABLE tbl_alerta
            ADD COLUMN id_parada_origen BIGINT REFERENCES tbl_parada (id_parada);
        UPDATE tbl_alerta a
           SET id_parada_origen = e.id_parada
          FROM tbl_estacion e
         WHERE e.id_estacion = a.id_estacion_origen;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_evento_talanquera_parada
    ON tbl_evento_talanquera (id_parada, tipo_evento, fecha_evento);
CREATE INDEX IF NOT EXISTS idx_parada_unidad_parada
    ON tbl_parada_unidad (id_parada);

