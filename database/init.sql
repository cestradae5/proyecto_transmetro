-- Infraestructura del sistema de transporte.
-- Creation flow: Municipalidad -> Linea -> Parada/Estacion -> Acceso.
-- A linea can exist before any parqueo, parada or estacion. Tables are
-- declared in FK dependency order (parqueo precedes linea because
-- tbl_linea.id_parqueo still references it).
CREATE TABLE IF NOT EXISTS tbl_municipalidad (
    id_municipalidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_municipalidad VARCHAR(120) NOT NULL UNIQUE,
    departamento VARCHAR(60) NOT NULL,
    estado_municipalidad VARCHAR(20) NOT NULL DEFAULT 'ACTIVA' CHECK (estado_municipalidad IN ('ACTIVA', 'INACTIVA'))
);

-- A parqueo is standalone (no FK to estacion); one parqueo can serve
-- several lineas through tbl_linea.id_parqueo.
CREATE TABLE IF NOT EXISTS tbl_parqueo (
    id_parqueo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_parqueo VARCHAR(120) NOT NULL,
    tipo_parqueo VARCHAR(50) NOT NULL,
    direccion TEXT NOT NULL,
    latitud DECIMAL(10,8) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud DECIMAL(11,8) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    capacidad_unidades INTEGER NOT NULL CHECK (capacidad_unidades >= 0),
    estado_parqueo VARCHAR(30) NOT NULL
);

-- id_parqueo is nullable: the linea is created first and its parqueo is
-- assigned later.
CREATE TABLE IF NOT EXISTS tbl_linea (
    id_linea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_linea VARCHAR(20) NOT NULL UNIQUE,
    nombre_linea VARCHAR(120) NOT NULL,
    color_hex VARCHAR(7) NOT NULL,
    estado_linea VARCHAR(20) NOT NULL CHECK (estado_linea IN ('ACTIVA', 'INACTIVA')),
    tipo_recorrido VARCHAR(20) NOT NULL CHECK (tipo_recorrido IN ('CIRCULAR', 'LINEAL')),
    id_parqueo BIGINT,
    FOREIGN KEY (id_parqueo) REFERENCES tbl_parqueo (id_parqueo)
);

-- Linea <-> Municipalidad is N:M.
CREATE TABLE IF NOT EXISTS tbl_linea_municipalidad (
    id_linea BIGINT NOT NULL,
    id_municipalidad BIGINT NOT NULL,
    PRIMARY KEY (id_linea, id_municipalidad),
    FOREIGN KEY (id_linea) REFERENCES tbl_linea (id_linea),
    FOREIGN KEY (id_municipalidad) REFERENCES tbl_municipalidad (id_municipalidad)
);

CREATE TABLE IF NOT EXISTS tbl_parada (
    id_parada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_parada VARCHAR(120) NOT NULL,
    latitud DECIMAL(10,8) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud DECIMAL(11,8) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    estado_parada VARCHAR(20) NOT NULL CHECK (estado_parada IN ('ACTIVA', 'CERRADA', 'MANTENIMIENTO')),
    capacidad_pasajeros INTEGER NOT NULL DEFAULT 100 CHECK (capacidad_pasajeros > 0)
);

-- An estacion is a 1:1 extension of a parada.
CREATE TABLE IF NOT EXISTS tbl_estacion (
    id_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estacion VARCHAR(120) NOT NULL,
    latitud DECIMAL(10,8) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud DECIMAL(11,8) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    estado_estacion VARCHAR(30) NOT NULL,
    id_parada BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada)
);

-- Accesos (entrances) belong to a parada.
CREATE TABLE IF NOT EXISTS tbl_acceso (
    id_acceso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parada BIGINT NOT NULL,
    nombre_acceso VARCHAR(120) NOT NULL,
    latitud DECIMAL(10,8) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud DECIMAL(11,8) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    tipo_acceso VARCHAR(20) NOT NULL CHECK (tipo_acceso IN ('PEATONAL', 'RAMPA', 'ESCALERA', 'ELEVADOR')),
    estado_acceso VARCHAR(20) NOT NULL DEFAULT 'HABILITADO' CHECK (estado_acceso IN ('HABILITADO', 'DESHABILITADO')),
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada)
);

CREATE TABLE IF NOT EXISTS tbl_linea_parada (
    id_linea_parada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden INTEGER NOT NULL CHECK (orden > 0),
    minutos_hasta_siguiente INTEGER NOT NULL CHECK (minutos_hasta_siguiente >= 0),
    id_parada BIGINT NOT NULL,
    id_linea BIGINT NOT NULL,
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada),
    FOREIGN KEY (id_linea) REFERENCES tbl_linea (id_linea),
    UNIQUE (id_linea, orden),
    UNIQUE (id_linea, id_parada)
);

CREATE TABLE IF NOT EXISTS tbl_estacion_linea (
    id_linea BIGINT NOT NULL,
    id_estacion BIGINT NOT NULL,
    tipo_punto VARCHAR(20) NOT NULL CHECK (tipo_punto IN ('PRINCIPAL', 'CONTROL', 'APOYO')),
    estado_asignacion VARCHAR(30) NOT NULL CHECK (estado_asignacion IN ('ACTIVA', 'INACTIVA')),
    PRIMARY KEY (id_linea, id_estacion),
    FOREIGN KEY (id_linea) REFERENCES tbl_linea (id_linea),
    FOREIGN KEY (id_estacion) REFERENCES tbl_estacion (id_estacion)
);

CREATE TABLE IF NOT EXISTS tbl_afectacion (
    id_afectacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_afectacion VARCHAR(50) NOT NULL,
    motivo TEXT NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ,
    estado_afectacion VARCHAR(30) NOT NULL,
    id_parada BIGINT,
    id_estacion BIGINT,
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada),
    FOREIGN KEY (id_estacion) REFERENCES tbl_estacion (id_estacion),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CHECK ((id_parada IS NOT NULL) <> (id_estacion IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS tbl_asignacion_estacion (
    id_asignacion_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_asignacion TIMESTAMPTZ NOT NULL,
    estado_asignacion VARCHAR(30) NOT NULL CHECK (estado_asignacion IN ('ACTIVA', 'INACTIVA')),
    id_empleado BIGINT NOT NULL,
    id_estacion BIGINT NOT NULL,
    FOREIGN KEY (id_empleado) REFERENCES tbl_empleado (id_emple),
    FOREIGN KEY (id_estacion) REFERENCES tbl_estacion (id_estacion)
);

-- Flota y asignaciones operativas.
