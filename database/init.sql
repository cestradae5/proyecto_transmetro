CREATE TABLE IF NOT EXISTS tbl_rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(100) NOT NULL UNIQUE,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    descrip_rol TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tbl_permiso (
    id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_permiso VARCHAR(80) NOT NULL UNIQUE,
    accion_permiso VARCHAR(160) NOT NULL
);

CREATE TABLE IF NOT EXISTS tbl_rol_permiso (
    id_rol BIGINT NOT NULL,
    id_permiso BIGINT NOT NULL,
    PRIMARY KEY (id_rol, id_permiso),
    FOREIGN KEY (id_rol) REFERENCES tbl_rol (id_rol) ON DELETE CASCADE,
    FOREIGN KEY (id_permiso) REFERENCES tbl_permiso (id_permiso) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tbl_empleado (
