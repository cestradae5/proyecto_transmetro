-- Conteo de pasajeros (ridership). Cada pasada por una talanquera es un
-- evento inmutable; la ocupación de una parada (sea o no estación) se
-- calcula a partir de los eventos, nunca se guarda como contador.
CREATE TABLE IF NOT EXISTS tbl_evento_talanquera (
    id_evento_talanquera BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parada BIGINT NOT NULL,
    id_tarjeta_ciudadana BIGINT NOT NULL,
    tipo_evento VARCHAR(10) NOT NULL CHECK (tipo_evento IN ('ENTRADA', 'SALIDA')),
    monto_cobrado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (monto_cobrado >= 0),
    clave_idempotencia VARCHAR(64) UNIQUE,
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada),
    FOREIGN KEY (id_tarjeta_ciudadana) REFERENCES tbl_tarjeta_ciudadana (id_tarjeta_ciudadana)
);

-- Una detención de una unidad en una parada: abre al llegar y cierra al salir.
-- La ocupación es una estimación (subieron - bajaron) y se arrastra de la
-- última parada cerrada de la unidad.
CREATE TABLE IF NOT EXISTS tbl_parada_unidad (
    id_parada_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad BIGINT NOT NULL,
    id_parada BIGINT NOT NULL,
    fecha_llegada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_salida TIMESTAMPTZ,
    ocupacion_llegada INTEGER NOT NULL CHECK (ocupacion_llegada >= 0),
    subieron INTEGER NOT NULL DEFAULT 0 CHECK (subieron >= 0),
    bajaron INTEGER NOT NULL DEFAULT 0 CHECK (bajaron >= 0),
    ocupacion_resultante INTEGER NOT NULL CHECK (ocupacion_resultante >= 0),
    minutos_espera_extra INTEGER NOT NULL DEFAULT 0 CHECK (minutos_espera_extra >= 0),
    FOREIGN KEY (id_unidad) REFERENCES tbl_unidad (id_unidad),
    FOREIGN KEY (id_parada) REFERENCES tbl_parada (id_parada)
);

-- Una unidad tiene a lo sumo una parada abierta a la vez.
CREATE UNIQUE INDEX IF NOT EXISTS idx_parada_unidad_abierta
    ON tbl_parada_unidad (id_unidad) WHERE fecha_salida IS NULL;

