    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_empleado BIGINT NOT NULL UNIQUE,
    id_unidad BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (id_empleado) REFERENCES tbl_empleado (id_emple),
    FOREIGN KEY (id_unidad) REFERENCES tbl_unidad (id_unidad)
);

-- Operación: alertas, novedades, historial y afectaciones.
CREATE TABLE IF NOT EXISTS tbl_alerta (
    id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_alerta VARCHAR(50) NOT NULL,
    tipo_origen VARCHAR(30) NOT NULL CHECK (tipo_origen IN ('UNIDAD', 'ESTACION')),
    tipo_destino VARCHAR(30) NOT NULL CHECK (tipo_destino IN ('CENTRAL', 'ESTACION')),
    estado_alerta VARCHAR(30) NOT NULL CHECK (estado_alerta IN ('PENDIENTE', 'RECIBIDA', 'EN_ATENCION', 'RESUELTA')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_unidad BIGINT,
    id_estacion_origen BIGINT,
    id_estacion_destino BIGINT,
    id_empleado BIGINT,
    FOREIGN KEY (id_unidad) REFERENCES tbl_unidad (id_unidad),
    FOREIGN KEY (id_estacion_origen) REFERENCES tbl_estacion (id_estacion),
    FOREIGN KEY (id_estacion_destino) REFERENCES tbl_estacion (id_estacion),
    FOREIGN KEY (id_empleado) REFERENCES tbl_empleado (id_emple)
);

